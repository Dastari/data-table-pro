import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const snapshotPath = path.join(
  rootDir,
  "api-snapshots",
  "public-api.md",
);
const declarationFiles = [
  "index.d.ts",
  "heroui.d.ts",
  "thegridcn.d.ts",
  "url-state.d.ts",
  "advanced.d.ts",
  "types.d.ts",
];
const packageJson = JSON.parse(
  await readFile(path.join(rootDir, "package.json"), "utf8"),
);
const sections = [
  "# Public API Snapshot",
  "",
  "This file is generated by `pnpm api:update`. Review changes to it as public API changes.",
  "",
  "## Package exports",
  "",
  "```json",
  JSON.stringify(packageJson.exports, null, 2),
  "```",
];

for (const filename of declarationFiles) {
  const contents = await readFile(
    path.join(rootDir, "dist", filename),
    "utf8",
  );
  sections.push(
    "",
    `## ${filename}`,
    "",
    "```ts",
    contents.trimEnd(),
    "```",
  );
}

const nextSnapshot = `${sections.join("\n")}\n`;
if (process.argv.includes("--update")) {
  await writeFile(snapshotPath, nextSnapshot);
  process.stdout.write(`Updated ${path.relative(rootDir, snapshotPath)}\n`);
} else {
  let currentSnapshot;
  try {
    currentSnapshot = await readFile(snapshotPath, "utf8");
  } catch {
    throw new Error(
      "The public API snapshot is missing. Run `pnpm api:update`.",
    );
  }
  if (currentSnapshot !== nextSnapshot) {
    throw new Error(
      "The public API snapshot is stale. Review the generated declarations and run `pnpm api:update`.",
    );
  }
  process.stdout.write("Public API snapshot is current\n");
}
